def fibonacci_rabbits(n, k):
    # n - номер месяца
    # k - число пар кроликов, рождающихся у каждой взрослой пары

    # Инициализация массива для динамического программирования
    # f[i] - число пар кроликов в i-ом месяце
    f = [0] * (n + 1)
    f[1] = 1  # В первый месяц одна пара

    for i in range(2, n + 1):
        if i == 2:
            f[i] = f[i - 1]  # Во второй месяц пары ещё не плодятся
        else:
            # Количество пар = количество пар в предыдущем месяце + количество пар в (i-2)-ом месяце * k
            f[i] = f[i - 1] + k * f[i - 2]

    return f[n]

# Пример использования
n = 5
k = 3
result = fibonacci_rabbits(n, k)
print(result)  # Ожидаемый вывод: 19
